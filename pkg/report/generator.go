func writeKnowledgeBaseSection(f *os.File) {
	f.WriteString("| TYPE | PAYLOAD | SUCCESS COUNT |\n")
	f.WriteString("| :--- | :--- | :--- |\n")

	if db.DB == nil {
		f.WriteString("| N/A | DB not initialized | 0 |\n")
		return
	}

	rows, err := db.DB.Query("SELECT vuln_type, payload, success_count FROM attack_patterns ORDER BY success_count DESC LIMIT 20")
	if err != nil {
		f.WriteString("| N/A | Knowledge base unavailable | 0 |\n")
		return
	}
	defer rows.Close()

	count := 0
	for rows.Next() {
		var vType, payload string
		var success int
		_ = rows.Scan(&vType, &payload, &success)
		payload = strings.ReplaceAll(payload, "|", "\\|")
		f.WriteString(fmt.Sprintf("| %s | `%s` | %d |\n", vType, payload, success))
		count++
	}

	if count == 0 {
		f.WriteString("| INFO | No learned vectors yet | 0 |\n")
	}
}

func progressBar(count, total int) string {
	if total <= 0 {
		return "░░░░░░░░░░"
	}
	if count < 0 {
		count = 0
	}
	if count > total {
		count = total
	}
	filled := int(float64(count) / float64(total) * 10.0)
	return strings.Repeat("█", filled) + strings.Repeat("░", 10-filled)
}

func getSeverityIcon(score float64) string {
	if score >= 9.0 {
		return "CRITICAL"
	}
	if score >= 7.0 {
		return "HIGH"
	}
	if score >= 4.0 {
		return "MEDIUM"
	}
	return "LOW"
}

